// Regenerates qa/functional/scenarios.md from the scenario definitions in results.json and ui-results.json
// (IDs, titles, type and expected outcome come from the suites themselves, so the catalogue never drifts).
import fs from 'node:fs';
import path from 'node:path';
import { HERE } from '../lib.mjs';

const api = JSON.parse(fs.readFileSync(path.join(HERE, 'results.json'), 'utf8'));
const ui = JSON.parse(fs.readFileSync(path.join(HERE, 'ui-results.json'), 'utf8'));

const AREAS = {
  health: ['Health & platform', 'None (anonymous).', 'GET /api/health, /api/health/ready, /api/auth/config; unknown routes; response headers.'],
  auth: ['Auth & session', 'qa-ft users created by the suite (pwchange, victim); QA admin used only for valid sign-in.', 'POST /api/auth/login, /logout, /change-password; GET /api/auth/me, /api/auth/sso/*; CSRF header + Origin rules.'],
  users: ['Users', 'Signed in as QA admin; fixtures qa-ft-<tag>-<suffix>@example.com.', 'GET/POST /api/admin/users, GET/PATCH /api/admin/users/{id}, POST …/reset-password, …/unlock, …/revoke-sessions.'],
  roles: ['Roles & module assignment', 'QA admin; viewer role modules captured and restored at the end.', 'GET /api/admin/roles, /api/admin/modules; PUT /api/admin/roles/{code}/modules.'],
  access: ['Module access matrix', 'Signed-in admin, analyst, viewer, analyst with denies (adeny), viewer with grants (vgrant), anonymous.', 'One representative GET per route group, compared across roles.'],
  market: ['Market data', 'Analyst (all analytics modules), viewer, adeny.', '/api/market/catalog, /years, /overview, /sections/{module}, /series/{key}, /series/{key}/export.csv, /forward-curves, /ytd-spreads, /oi-cumulative, /ta/*.'],
  snd: ['Intel · SND', 'Admin (upload/delete), analyst (read), viewer (no module). Test source indonesia/2099 removed at the end.', '/api/intel/snd/graphs|tables|exports|sources, POST/DELETE /api/intel/snd/sources.'],
  cftc: ['Intel · CFTC', 'No worker: jobs stay queued.', 'GET /api/intel/cftc, POST /api/intel/cftc/refresh.'],
  calendar: ['Intel · Calendar', 'No Anthropic key configured.', 'GET /api/intel/calendar, POST /api/intel/calendar/refresh.'],
  atlas: ['Intel · HVO/SAF Atlas', 'Original 94-plant dataset captured first and restored after every mutating case.', 'GET/PUT /api/intel/atlas.'],
  ai: ['Intel · AI analysis', 'No Anthropic key: narrative skipped. Dedicated qa-ft-ratelimit analyst for the 20/hour limit.', '/api/intel/ai/instruments, POST/GET /api/intel/ai/reports, GET /api/intel/ai/reports/{id}.'],
  news: ['Intel · News & documents', 'No Anthropic key: uploads refused with 409 before validation.', '/api/intel/news/panel, /news/documents (GET/POST), …/{id}/reprocess, DELETE …/{id}.'],
  waste_bio: ['Sheets · Waste/Bio', 'Synthetic Argus data loaded.', '/api/sheets/waste-bio/curves/{set}, /ytd, /arb, /tickets-calc.'],
  parity: ['Sheets · Parity Ind/China', 'Synthetic parity snapshots loaded.', '/api/sheets/parity-snapshots.'],
  'sheets-admin': ['Admin · Sheet sources', 'QA admin; no service-account key and no uploads before the run (verified); throwaway RSA key generated in-process and removed.', 'GET /api/admin/sheets, POST /refresh, PUT/DELETE /service-account, POST /upload, DELETE /upload/{code}.'],
  admin: ['Admin · Audit log', 'QA admin; events produced by the suite.', 'GET /api/admin/audit, /api/admin/audit/export.csv.'],
  settings: ['Admin · Settings', 'Original values captured and restored.', 'GET/PUT /api/admin/settings.'],
  pipeline: ['Admin · Data pipeline', 'At most one recompute run is queued (never full); no worker.', 'GET /api/admin/pipeline/status, /runs, /runs/{id}; POST /api/admin/pipeline/run.'],
  'ui-auth': ['UI · Sign-in, session, password', 'Browser pane tab-1 at http://localhost:5181; qa-ft-ui-* users from tools/ui-fixtures.mjs.', 'Login page, user menu, /change-password.'],
  'ui-access': ['UI · Navigation & access', 'Viewer, analyst and admin qa-ft-ui users.', 'Sidebar, sub-navigation, guarded routes.'],
  'ui-pages': ['UI · Page rendering', 'qa-ft-ui-admin; console checked after each batch.', 'Every analytics, intel and admin page.'],
  'ui-admin': ['UI · Admin dialogs & forms', 'qa-ft-ui-admin.', 'Users dialog, Roles matrix, Settings, Sheet sources, Audit, Pipeline.'],
  'ui-intel': ['UI · Intelligence pages', 'qa-ft-ui-admin.', 'AI Analysis, Atlas.'],
};

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
let md = `# AASTAR Price Dashboard — functional test scenarios

Generated by \`qa/functional/tools/make-scenarios.mjs\` from the executable suites
(\`api-suite.mjs\` → \`results.json\`, browser run → \`ui-results.json\`). The **Title / steps** column states the
action (request or UI step) and the inputs; **Expected** is the pass criterion the suite asserts.

Common preconditions: QA stack running (API 127.0.0.1:8710 behind the Vite proxy 127.0.0.1:5181, PostgreSQL 18 on
5546, demo data from 2024-01-02, four sheet sources loaded, 94 atlas plants); no worker; no external integrations.
The suite creates its own \`qa-ft-<tag>-<epoch>@example.com\` users (analyst, analyst2, ratelimit, viewer, victim,
pwchange, disabled, vgrant = viewer + grants for ai/news/cftc/snd/atlas/calendar/waste_bio, adeny = analyst − overview,
parity, waste_bio, calendar_spreads) and every unsafe call sends \`Origin\` + \`X-CSRF-Token\` unless the case says otherwise.

| Area | Scenarios | Positive | Negative |
|---|---|---|---|
`;
const all = [...api, ...ui];
const order = Object.keys(AREAS);
const areas = [...new Set(all.map((r) => r.area))].sort((a, b) => order.indexOf(a) - order.indexOf(b));
for (const a of areas) {
  const rs = all.filter((r) => r.area === a);
  md += `| ${AREAS[a]?.[0] ?? a} | ${rs.length} | ${rs.filter((r) => r.type === 'Positive').length} | ${rs.filter((r) => r.type === 'Negative').length} |\n`;
}
md += `| **Total** | **${all.length}** | **${all.filter((r) => r.type === 'Positive').length}** | **${all.filter((r) => r.type === 'Negative').length}** |\n`;

for (const a of areas) {
  const [name, pre, routes] = AREAS[a] ?? [a, '', ''];
  md += `\n## ${name}\n\n**Preconditions:** ${pre}  \n**Surface:** ${routes}\n\n| ID | Title / steps | P/N | Expected |\n|---|---|---|---|\n`;
  for (const r of all.filter((x) => x.area === a)) md += `| ${r.id} | ${esc(r.title)} | ${r.type === 'Positive' ? 'P' : 'N'} | ${esc(r.expected)} |\n`;
}
fs.writeFileSync(path.join(HERE, 'scenarios.md'), md);
console.log(`scenarios.md: ${all.length} scenarios in ${areas.length} areas`);
